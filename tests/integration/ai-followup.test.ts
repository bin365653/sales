import { afterAll, describe, expect, it } from "vitest";
import { prisma } from "@/server/db";
import {
  cleanupTestUsers,
  createTestUser,
  registerTestModelConfig,
} from "./helpers";
import { createLead } from "@/server/services/leads";
import { createModelConfig } from "@/server/ai/model-configs";
import { createAiRun, executeRun } from "@/server/ai/runner";

// V2.0-T11 集成：followup_advice 全链路（快照注入 followup_context →
// 执行成功 → 输出留痕）+ analysis/call_prep v2 快照带 profile_v2；
// 业务零写回的红线断言在 ai-redline.test.ts（T12）。

afterAll(cleanupTestUsers);

const SECRET_KEY = "sk-integration-secret-9876543210";

const VALID_FOLLOWUP = {
  reason_explanation: "该客户软件 2026-12 到期，处于半年内窗口，系统按月度规则生成本月跟进任务。",
  communication_advice: "核实续费意向与时间表；顺带确认当前系统使用痛点。",
};

function okResponse(content: string): Response {
  return new Response(
    JSON.stringify({ choices: [{ message: { role: "assistant", content } }] }),
    { status: 200, headers: { "Content-Type": "application/json" } },
  );
}

async function setupCase() {
  const admin = await createTestUser("admin");
  const sales = await createTestUser("sales");
  const config = await createModelConfig(admin, {
    baseUrl: "https://api.mock-provider.local/v1",
    modelName: "mock-model",
    apiKey: SECRET_KEY,
    timeoutMs: 5000,
    maxRetries: 1,
    isActive: true,
  });
  registerTestModelConfig(config.id);
  const lead = await createLead(sales, {
    name: "T11 跟进策略客户",
    currentSystem: "手工台账（Excel/纸质）",
  });
  return { sales, lead };
}

describe("followup_advice 全链路（V2.0-T11）", () => {
  it("创建 → 快照含 followup_context 与 profile_v2 → 执行成功输出留痕", async () => {
    const { sales, lead } = await setupCase();

    // 造一条 pending 自动任务（月度）供快照携带
    await prisma.task.create({
      data: {
        leadId: lead.id,
        assigneeId: sales.id,
        createdBy: sales.id,
        type: "follow_up",
        title: "软件到期月度跟进（2026-11）",
        dueAt: new Date(),
        sourceType: "expiry_monthly",
        autoGenerated: true,
        priority: 3,
      },
    });

    const run = await createAiRun(
      sales,
      { leadId: lead.id, runType: "followup_advice" },
      { execute: false },
    );
    expect(run.status).toBe("pending");
    const snapshot = run.inputSnapshot as Record<string, unknown>;
    // followup_context 注入（任务来源+策略快照）
    const followup = snapshot.followup_context as {
      pending_tasks: { source_type: string; title: string }[];
    };
    expect(followup.pending_tasks).toHaveLength(1);
    expect(followup.pending_tasks[0]!.source_type).toBe("expiry_monthly");
    // profile_v2 组（象限/核实状态汇总；无联系方式/核实人）
    const v2 = snapshot.profile_v2 as Record<string, unknown>;
    expect(v2.quadrant_code).toBeNull();
    expect(typeof v2.verification_summary).toBe("object");
    expect(JSON.stringify(snapshot)).not.toContain("verifiedBy");

    const finished = await executeRun(run.id, {
      fetchImpl: async () => okResponse(JSON.stringify(VALID_FOLLOWUP)),
    });
    expect(finished.status).toBe("success");
    expect(finished.output).toMatchObject({
      reason_explanation: expect.stringContaining("月度"),
      communication_advice: expect.any(String),
    });
  });

  it("analysis/call_prep v2：快照带 profile_v2 核实状态汇总（v2 提示词输入）", async () => {
    const { sales, lead } = await setupCase();
    const run = await createAiRun(
      sales,
      { leadId: lead.id, runType: "analysis" },
      { execute: false },
    );
    const snapshot = run.inputSnapshot as Record<string, unknown>;
    expect(snapshot.profile_v2).toBeDefined();
    expect((snapshot.profile_v2 as Record<string, unknown>).contract_expiry_window).toBeDefined();
    expect(snapshot.followup_context).toBeUndefined();
  });

  it("结构非法自动纠错重试 1 次后仍失败 → invalid_output（可人工重试）", async () => {
    const { sales, lead } = await setupCase();
    const run = await createAiRun(
      sales,
      { leadId: lead.id, runType: "followup_advice" },
      { execute: false },
    );
    let calls = 0;
    const finished = await executeRun(run.id, {
      fetchImpl: async () => {
        calls += 1;
        return okResponse('{"oops": true}');
      },
    });
    expect(finished.status).toBe("invalid_output");
    expect(calls).toBe(2); // 初次 + 纠错重试 1 次
  });
});
