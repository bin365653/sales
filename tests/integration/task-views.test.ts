import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { prisma } from "@/server/db";
import {
  cleanupTestUsers,
  createTestUser,
  getPresetStage,
  uniqueSuffix,
  type TestUser,
} from "./helpers";
import { listTasks, getTaskCounts } from "@/server/services/tasks";
import { countLeadsByExpiryView } from "@/server/services/leads";
import { addExpiryMonths, currentExpiryMonth } from "@/lib/expiry";
import type { TaskListQuery } from "@/lib/schemas/task";

// V2.0-T07 任务中心与到期视图验收：
// ② 任务排序 priority 1→5（约定→预约→月度→画像→周期），同优先级按逾期与阶段；
// ③ manual（约定）任务恒排前（不被自动任务覆盖）；
// ① 四视图计数与 SQL 对账（countLeadsByExpiryView 与列表筛选同一实现）；
// 来源筛选（manual/expiry_monthly/quadrant_periodic/profile_gap）。

const owner: { value: TestUser | null } = { value: null };
const createdLeadIds: string[] = [];

beforeAll(async () => {
  owner.value = await createTestUser("admin");
});

afterAll(async () => {
  if (createdLeadIds.length > 0) {
    await prisma.task.deleteMany({ where: { leadId: { in: createdLeadIds } } });
    await prisma.followUpCycle.deleteMany({ where: { leadId: { in: createdLeadIds } } });
    await prisma.leadFieldVerification.deleteMany({ where: { leadId: { in: createdLeadIds } } });
    await prisma.leadEvent.deleteMany({ where: { leadId: { in: createdLeadIds } } });
    await prisma.lead.deleteMany({ where: { id: { in: createdLeadIds } } });
  }
  await cleanupTestUsers();
});

async function createLeadFixture(options: { expiryMonth?: string } = {}): Promise<string> {
  const stage = await getPresetStage("to_contact");
  const lead = await prisma.lead.create({
    data: {
      name: `T07 视图夹具 ${uniqueSuffix()}`,
      ownerId: owner.value!.id,
      stageId: stage.id,
      contractExpiry: options.expiryMonth
        ? new Date(`${options.expiryMonth}-01T00:00:00.000Z`)
        : null,
    },
    select: { id: true },
  });
  createdLeadIds.push(lead.id);
  if (options.expiryMonth) {
    await prisma.leadFieldVerification.create({
      data: { leadId: lead.id, fieldKey: "contract_expiry", status: "confirmed", source: "manual" },
    });
  }
  return lead.id;
}

async function createTaskFixture(params: {
  leadId: string;
  title: string;
  sourceType: "manual" | "expiry_monthly" | "profile_gap" | "quadrant_periodic";
  priority: number;
  /** 相对今天的偏移天数（负=逾期） */
  dueOffsetDays: number;
  stageOffset?: number;
}) {
  return prisma.task.create({
    data: {
      leadId: params.leadId,
      assigneeId: owner.value!.id,
      createdBy: owner.value!.id,
      type: "follow_up",
      title: params.title,
      dueAt: new Date(Date.now() + params.dueOffsetDays * 24 * 3600 * 1000),
      sourceType: params.sourceType,
      priority: params.priority,
      autoGenerated: params.sourceType !== "manual",
    },
    select: { id: true, title: true },
  });
}

function queryOf(overrides: Partial<TaskListQuery> = {}): TaskListQuery {
  return {
    view: "all",
    status: "pending",
    sourceType: "all",
    page: 1,
    pageSize: 50,
    ...overrides,
  };
}

describe("任务中心排序与来源筛选（V2.0-T07）", () => {
  it("排序 priority 1→5：约定(1) → 预约演示(2) → 月度(3) → 画像(4) → 周期(5)", async () => {
    const lead = await createLeadFixture();
    // 故意按乱序插入
    await createTaskFixture({ leadId: lead, title: "T07周期", sourceType: "quadrant_periodic", priority: 5, dueOffsetDays: -5 });
    await createTaskFixture({ leadId: lead, title: "T07月度", sourceType: "expiry_monthly", priority: 3, dueOffsetDays: 0 });
    await createTaskFixture({ leadId: lead, title: "T07画像", sourceType: "profile_gap", priority: 4, dueOffsetDays: -2 });
    await createTaskFixture({ leadId: lead, title: "T07约定", sourceType: "manual", priority: 1, dueOffsetDays: 3 });
    await createTaskFixture({ leadId: lead, title: "T07演示", sourceType: "manual", priority: 2, dueOffsetDays: 2 });

    const result = await listTasks(owner.value!, queryOf());
    const titles = result.items
      .filter((task) => task.leadId === lead)
      .map((task) => task.title);
    expect(titles).toEqual(["T07约定", "T07演示", "T07月度", "T07画像", "T07周期"]);
  });

  it("来源筛选只返回对应来源；manual 筛选含约定与预约", async () => {
    const result = await listTasks(owner.value!, queryOf({ sourceType: "quadrant_periodic" }));
    expect(result.items.every((task) => task.sourceType === "quadrant_periodic")).toBe(true);
    const manual = await listTasks(owner.value!, queryOf({ sourceType: "manual" }));
    expect(manual.items.every((task) => task.sourceType === "manual")).toBe(true);
  });

  it("今日视图计数：今天到期的自动任务计入今日、不计逾期（逾期视图联动）", async () => {
    const before = await getTaskCounts(owner.value!);
    const lead = await createLeadFixture();
    await createTaskFixture({ leadId: lead, title: "T07今天到期", sourceType: "expiry_monthly", priority: 3, dueOffsetDays: 0 });
    const after = await getTaskCounts(owner.value!);
    expect(after.today).toBe(before.today + 1);
    expect(after.overdue).toBe(before.overdue);
  });

  it("四视图计数与 SQL 对账（同一 where 实现）", async () => {
    const month = currentExpiryMonth(new Date());
    await createLeadFixture({ expiryMonth: addExpiryMonths(month, 2) });
    await createLeadFixture({ expiryMonth: addExpiryMonths(month, 9) });
    await createLeadFixture({ expiryMonth: addExpiryMonths(month, -1) });

    const counts = await countLeadsByExpiryView(owner.value!);
    // 对账：直接按同一条件 SQL 计数
    const monthStart = new Date(`${month}-01T00:00:00.000Z`);
    const plus = (n: number) => new Date(`${addExpiryMonths(month, n)}-01T00:00:00.000Z`);
    const [within6, within1, expired, unknown] = await Promise.all([
      prisma.lead.count({ where: { deletedAt: null, contractExpiry: { gte: monthStart, lte: plus(6) } } }),
      prisma.lead.count({ where: { deletedAt: null, contractExpiry: { gte: monthStart, lte: plus(1) } } }),
      prisma.lead.count({ where: { deletedAt: null, contractExpiry: { lt: monthStart } } }),
      prisma.lead.count({
        where: {
          deletedAt: null,
          OR: [
            { contractExpiry: null },
            { fieldVerifications: { some: { fieldKey: "contract_expiry", status: "unknown" } } },
          ],
        },
      }),
    ]);
    expect(counts.within_6m).toBe(within6);
    expect(counts.within_1m).toBe(within1);
    expect(counts.expired).toBe(expired);
    expect(counts.unknown).toBe(unknown);
  });
});
