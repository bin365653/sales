// V2.0-T06 验收（实施计划 §8：《迭代开发V2.2》验收 10 项逐条自动化）：
// ① 6 个月边界（恰 6 个月生成月度/7 个月不生成改走象限周期）
// ② 到期日期更新重算保历史（旧周期任务取消留痕、当月月度生成、done 不动）
// ③ 到期未知 → 画像补充任务
// ④ 到期已过 → 到期状态核实任务
// ⑤ 同客户同周期重复执行不重复（串行两轮 + 并发双事务各仅 1 条）
// ⑥ 客户主动约定任务不被覆盖（约定优先跳过周期任务）
// ⑦ 已成交客户停止生成且流转时取消 pending 自动任务
// ⑧ 分类变化重算（旧计划取消、新策略计划生成、quadrant_changed+plan_changed 齐备）
// ⑨ 已完成任务不被改动
// ⑩ 逾期任务正确计数（生成任务 dueAt=今天 → 计入今日不计逾期）

const admin: { value: TestUser | null } = { value: null };
const createdLeadIds: string[] = [];

beforeAll(async () => {
  admin.value = await createTestUser("admin");
});

afterAll(async () => {
  if (createdLeadIds.length > 0) {
    await prisma.task.deleteMany({ where: { leadId: { in: createdLeadIds } } });
    await prisma.followUpCycle.deleteMany({ where: { leadId: { in: createdLeadIds } } });
    await prisma.leadFieldVerification.deleteMany({ where: { leadId: { in: createdLeadIds } } });
    await prisma.leadEvent.deleteMany({ where: { leadId: { in: createdLeadIds } } });
    await prisma.lead.deleteMany({ where: { id: { in: createdLeadIds } } });
  }
  await prisma.auditLog.deleteMany({
    where: { action: { in: ["task_generation_failed", "task_generation_manual"] } },
  });
  await cleanupTestUsers();
});

/** 夹具客户：直接落库（与生成引擎同口径的核实行由本助手一并创建） */
async function createLeadFixture(options: {
  quadrant?: "a" | "b" | "c" | "d" | null;
  /** 到期月 "YYYY-MM"；不传 = 到期未知 */
  expiryMonth?: string;
  expiryStatus?: "unverified" | "confirmed" | "stated" | "unknown";
  stageSemanticKey?: string;
  /** 锚点前移天数（createdAt 回填，模拟老客户欠账） */
  backdateDays?: number;
}): Promise<{ id: string; name: string }> {
  const stage = await getPresetStage(options.stageSemanticKey ?? "to_contact");
  const backdate = options.backdateDays ?? 0;
  const name = `T06 生成夹具 ${uniqueSuffix()}`;
  const lead = await prisma.lead.create({
    data: {
      name,
      ownerId: admin.value!.id,
      stageId: stage.id,
      quadrantCode: options.quadrant ?? null,
      contractExpiry: options.expiryMonth
        ? new Date(`${options.expiryMonth}-01T00:00:00.000Z`)
        : null,
      ...(backdate > 0
        ? { createdAt: new Date(Date.now() - backdate * 24 * 3600 * 1000) }
        : {}),
    },
    select: { id: true },
  });
  createdLeadIds.push(lead.id);
  if (options.expiryMonth) {
    await prisma.leadFieldVerification.create({
      data: {
        leadId: lead.id,
        fieldKey: "contract_expiry",
        status: options.expiryStatus ?? "confirmed",
        source: "manual",
      },
    });
  }
  return { id: lead.id, name };
}

async function pendingAutoTasks(leadId: string) {
  return prisma.task.findMany({
    where: { leadId, status: "pending", autoGenerated: true },
  });
}

/** 上海日历日（dueAt 的时区口径断言用；UTC 取日期会差一天） */
function shanghaiDate(date: Date): string {
  return new Intl.DateTimeFormat("en-CA", {
    timeZone: "Asia/Shanghai",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).format(date);
}

describe("生成引擎：到期窗口与四源", () => {
  it("验收①：恰 6 个月后到期 → 当月月度任务；7 个月后 → 无月度、按象限周期（欠账客户）", async () => {
    const month = currentExpiryMonth(new Date());
    const within = await createLeadFixture({ quadrant: "a", expiryMonth: addExpiryMonths(month, 6) });
    const beyond = await createLeadFixture({
      quadrant: "a",
      expiryMonth: addExpiryMonths(month, 7),
      backdateDays: 45,
    });

    const statsWithin = await runTaskGeneration({ leadIds: [within.id], actorId: admin.value!.id });
    const statsBeyond = await runTaskGeneration({ leadIds: [beyond.id], actorId: admin.value!.id });

    // 恰 6 个月 → 月度任务（含第 6 个月边界）
    expect(statsWithin.createdTasks).toBe(1);
    const monthly = await pendingAutoTasks(within.id);
    expect(monthly).toHaveLength(1);
    expect(monthly[0]).toMatchObject({
      sourceType: "expiry_monthly",
      priority: 3,
      title: `软件到期月度跟进（${month}）`,
    });
    // 7 个月 → 无月度；A 策略 30 天、anchor 45 天前 → 欠账补当前一轮 dueAt=今天
    expect(statsBeyond.createdTasks).toBe(1);
    const periodic = await pendingAutoTasks(beyond.id);
    expect(periodic).toHaveLength(1);
    expect(periodic[0]).toMatchObject({ sourceType: "quadrant_periodic", priority: 5 });
    // 欠账收敛到今天（上海日历日）
    expect(shanghaiDate(periodic[0]!.dueAt)).toBe(shanghaiDate(new Date()));

    // 周期台账：月度行 M{当月}；周期行轮次 '1'
    const cycles = await prisma.followUpCycle.findMany({
      where: { leadId: { in: [within.id, beyond.id] } },
    });
    expect(cycles.map((c) => c.cycleKey).sort()).toEqual(["1", `M${month}`].sort());
  });

  it("验收③：到期未知 → 画像补充任务（不套长期策略，即使象限已定）", async () => {
    const lead = await createLeadFixture({ quadrant: "a" });
    const stats = await runTaskGeneration({ leadIds: [lead.id], actorId: admin.value!.id });
    expect(stats.createdTasks).toBe(1);
    const tasks = await pendingAutoTasks(lead.id);
    expect(tasks[0]).toMatchObject({ sourceType: "profile_gap", priority: 4, title: "画像补充核实" });
    // dueAt = 今天 + 3 天（提前量默认）
    const dueDays = Math.round(
      (tasks[0]!.dueAt.getTime() - new Date().getTime()) / (24 * 3600 * 1000),
    );
    expect(dueDays).toBeGreaterThanOrEqual(2);
    expect(dueDays).toBeLessThanOrEqual(4);
  });

  it("验收④：到期已过 → 到期状态核实任务，原因文案为持续核实", async () => {
    const month = currentExpiryMonth(new Date());
    const lead = await createLeadFixture({
      quadrant: "a",
      expiryMonth: addExpiryMonths(month, -2),
    });
    const stats = await runTaskGeneration({ leadIds: [lead.id], actorId: admin.value!.id });
    expect(stats.createdTasks).toBe(1);
    const tasks = await pendingAutoTasks(lead.id);
    expect(tasks[0]).toMatchObject({ sourceType: "expiry_monthly", title: "软件到期状态核实" });
  });
});

describe("生成引擎：防重复与约定优先", () => {
  it("验收⑤：同客户同周期重复执行不重复（串行两轮 created=0）；并发双事务各仅 1 条", async () => {
    const month = currentExpiryMonth(new Date());
    const lead = await createLeadFixture({ quadrant: "a", expiryMonth: addExpiryMonths(month, 3) });

    const first = await runTaskGeneration({ leadIds: [lead.id], actorId: admin.value!.id });
    expect(first.createdTasks).toBe(1);
    const second = await runTaskGeneration({ leadIds: [lead.id], actorId: admin.value!.id });
    expect(second.createdTasks).toBe(0);
    expect(await prisma.task.count({ where: { leadId: lead.id, sourceType: "expiry_monthly" } })).toBe(1);

    // 并发：全新客户 + 两个并行生成（部分唯一索引兜底，P2002 捕获跳过）
    const concurrent = await createLeadFixture({
      quadrant: "a",
      expiryMonth: addExpiryMonths(month, 4),
    });
    const [a, b] = await Promise.all([
      runTaskGeneration({ leadIds: [concurrent.id], actorId: admin.value!.id }),
      runTaskGeneration({ leadIds: [concurrent.id], actorId: admin.value!.id }),
    ]);
    expect(a.createdTasks + b.createdTasks + a.skippedTasks + b.skippedTasks).toBeGreaterThanOrEqual(1);
    expect(
      await prisma.task.count({ where: { leadId: concurrent.id, sourceType: "expiry_monthly" } }),
    ).toBe(1);
  });

  it("验收⑥：客户主动约定的 pending 任务不被覆盖——周期任务本轮跳过", async () => {
    const month = currentExpiryMonth(new Date());
    const lead = await createLeadFixture({
      quadrant: "a",
      expiryMonth: addExpiryMonths(month, 12),
      backdateDays: 60,
    });
    await prisma.task.create({
      data: {
        leadId: lead.id,
        assigneeId: admin.value!.id,
        createdBy: admin.value!.id,
        type: "follow_up",
        title: "T06 客户约定：周四下午再联系",
        dueAt: new Date(Date.now() + 2 * 24 * 3600 * 1000),
        sourceType: "manual",
        priority: 1,
      },
    });

    const stats = await runTaskGeneration({ leadIds: [lead.id], actorId: admin.value!.id });
    expect(stats.createdTasks).toBe(0);
    const tasks = await prisma.task.findMany({ where: { leadId: lead.id, status: "pending" } });
    expect(tasks).toHaveLength(1);
    expect(tasks[0]!.title).toBe("T06 客户约定：周四下午再联系");
    expect(tasks[0]!.sourceType).toBe("manual");
  });

  it("验收⑦：已成交客户不生成；流转到 won 时 pending 自动任务全部取消", async () => {
    const month = currentExpiryMonth(new Date());
    // won 客户不在扫描范围
    const wonLead = await createLeadFixture({
      quadrant: "a",
      expiryMonth: addExpiryMonths(month, 2),
      stageSemanticKey: "won",
    });
    const stats = await runTaskGeneration({ leadIds: [wonLead.id], actorId: admin.value!.id });
    expect(stats.createdTasks).toBe(0);

    // 活跃客户先生成月度任务，再流转到 won → pending 自动任务被取消（recalc）
    const lead = await createLeadFixture({ quadrant: "a", expiryMonth: addExpiryMonths(month, 2) });
    await runTaskGeneration({ leadIds: [lead.id], actorId: admin.value!.id });
    expect(await pendingAutoTasks(lead.id)).toHaveLength(1);

    const leadRow = await prisma.lead.findUniqueOrThrow({ where: { id: lead.id } });
    await transitionStage(admin.value!, lead.id, {
      stageId: (await getPresetStage("won")).id,
      dataVersion: leadRow.dataVersion,
    });

    expect(await pendingAutoTasks(lead.id)).toHaveLength(0);
    const canceled = await prisma.task.findFirst({
      where: { leadId: lead.id, sourceType: "expiry_monthly" },
    });
    expect(canceled!.status).toBe("canceled");
    expect(canceled!.originalDueAt).not.toBeNull();
    const event = await prisma.leadEvent.findFirst({
      where: { leadId: lead.id, eventType: "plan_changed" },
      orderBy: { occurredAt: "desc" },
    });
    expect(event).not.toBeNull();
    expect((event!.detail as { reason: string }).reason).toBe("stage_changed");
  });
});

describe("生成引擎：动态重算（§4.6 五触发）", () => {
  it("验收②+⑨：到期日期更新 → 旧周期任务取消（original_due_at 留痕）+ 当月月度生成 + done 历史不动", async () => {
    const month = currentExpiryMonth(new Date());
    const lead = await createLeadFixture({
      quadrant: "a",
      expiryMonth: addExpiryMonths(month, 12),
      backdateDays: 60,
    });
    await runTaskGeneration({ leadIds: [lead.id], actorId: admin.value!.id });
    const oldTask = (await pendingAutoTasks(lead.id))[0]!;
    // 历史完成任务
    await prisma.task.create({
      data: {
        leadId: lead.id,
        assigneeId: admin.value!.id,
        createdBy: admin.value!.id,
        type: "follow_up",
        title: "T06 历史-已完成",
        dueAt: new Date(Date.now() - 10 * 24 * 3600 * 1000),
        status: "done",
        completedAt: new Date(Date.now() - 9 * 24 * 3600 * 1000),
        sourceType: "quadrant_periodic",
        autoGenerated: true,
        priority: 5,
      },
    });

    // 触发：编辑保存把到期改为下月（within_6m）
    const before = await prisma.lead.findUniqueOrThrow({ where: { id: lead.id } });
    await updateLead(admin.value!, lead.id, {
      dataVersion: before.dataVersion,
      contractExpiry: `${addExpiryMonths(month, 1)}-01`,
    });

    // 旧周期任务取消 + 留痕；当月月度任务生成；done 任务原样
    expect((await prisma.task.findUniqueOrThrow({ where: { id: oldTask.id } })).status).toBe(
      "canceled",
    );
    const afterTasks = await prisma.task.findMany({ where: { leadId: lead.id } });
    const monthly = afterTasks.find((task) => task.sourceType === "expiry_monthly");
    expect(monthly?.status).toBe("pending");
    const doneTask = afterTasks.find((task) => task.status === "done");
    expect(doneTask).toBeDefined();
    expect(doneTask!.completedAt).not.toBeNull();

    // plan_changed 事件：reason=expiry_updated、canceledTaskIds 含旧任务
    const event = await prisma.leadEvent.findFirst({
      where: { leadId: lead.id, eventType: "plan_changed" },
      orderBy: { occurredAt: "desc" },
    });
    expect((event!.detail as { reason: string }).reason).toBe("expiry_updated");
    expect(
      (event!.detail as { canceledTaskIds: string[] }).canceledTaskIds,
    ).toContain(oldTask.id);
    expect(
      ((event!.detail as { createdCycleKeys: string[] }).createdCycleKeys ?? []).length,
    ).toBeGreaterThan(0);
  });

  it("到期从未知变为半年内：画像补充任务取消、月度任务接管", async () => {
    const month = currentExpiryMonth(new Date());
    const lead = await createLeadFixture({ quadrant: "a" });
    await runTaskGeneration({ leadIds: [lead.id], actorId: admin.value!.id });
    expect((await pendingAutoTasks(lead.id))[0]!.sourceType).toBe("profile_gap");

    const before = await prisma.lead.findUniqueOrThrow({ where: { id: lead.id } });
    await updateLead(admin.value!, lead.id, {
      dataVersion: before.dataVersion,
      contractExpiry: `${addExpiryMonths(month, 2)}-01`,
    });

    const tasks = await prisma.task.findMany({ where: { leadId: lead.id, status: "pending" } });
    expect(tasks).toHaveLength(1);
    expect(tasks[0]!.sourceType).toBe("expiry_monthly");
    const gapTasks = await prisma.task.findMany({
      where: { leadId: lead.id, sourceType: "profile_gap" },
    });
    expect(gapTasks.every((task) => task.status === "canceled")).toBe(true);
  });

  it("验收⑧：分类变化（意愿改无）→ 旧 A 周期任务取消、按 B 策略重建、quadrant_changed+plan_changed 齐备", async () => {
    const month = currentExpiryMonth(new Date());
    const lead = await createLeadFixture({
      quadrant: "a",
      expiryMonth: addExpiryMonths(month, 12),
      backdateDays: 60,
    });
    // 补齐分类轴核实行（模拟已画像客户）
    await prisma.lead.update({ where: { id: lead.id }, data: { nextGenMobileOrder: true, qinceInterest: true } });
    await prisma.leadFieldVerification.create({
      data: { leadId: lead.id, fieldKey: "next_gen_mobile_order", status: "confirmed", source: "manual" },
    });
    await prisma.leadFieldVerification.create({
      data: { leadId: lead.id, fieldKey: "qince_interest", status: "confirmed", source: "manual" },
    });
    await runTaskGeneration({ leadIds: [lead.id], actorId: admin.value!.id });
    const oldTask = (await pendingAutoTasks(lead.id))[0]!;
    expect(oldTask.sourceType).toBe("quadrant_periodic");

    // 编辑：意愿改否 + 显式确认状态（与沟通确认链路一致——值变化自动置
    // unverified，须同时提交显式状态才保持已确认；象限 a→b）
    const before = await prisma.lead.findUniqueOrThrow({ where: { id: lead.id } });
    await updateLead(admin.value!, lead.id, {
      dataVersion: before.dataVersion,
      qinceInterest: false,
      verifications: { qince_interest: "confirmed" },
    });

    const after = await prisma.lead.findUniqueOrThrow({ where: { id: lead.id } });
    expect(after.quadrantCode).toBe("b");
    // 旧 A 任务取消；新 B 计划按 anchor=quadrant_computed_at（刚刷新=现在）
    // 排期到 60 天后 → 当前不生成（§4.5 anchor 语义），旧计划已清空
    expect((await prisma.task.findUniqueOrThrow({ where: { id: oldTask.id } })).status).toBe(
      "canceled",
    );
    expect(await pendingAutoTasks(lead.id)).toHaveLength(0);
    // 事件链：quadrant_changed + plan_changed 只追加
    const events = await prisma.leadEvent.findMany({
      where: { leadId: lead.id, eventType: { in: ["quadrant_changed", "plan_changed"] } },
      orderBy: { occurredAt: "asc" },
    });
    expect(events.map((event) => event.eventType)).toEqual(["quadrant_changed", "plan_changed"]);
    expect((events[1]!.detail as { reason: string }).reason).toBe("interest_updated");

    // 未来窗口到达（模拟 61 天后）：B 策略周期任务自动生成（欠账收敛到模拟的今天）
    const futureStats = await runTaskGeneration({
      leadIds: [lead.id],
      actorId: admin.value!.id,
      now: new Date(Date.now() + 61 * 24 * 3600 * 1000),
    });
    expect(futureStats.createdTasks).toBe(1);
    const futureTasks = await prisma.task.findMany({
      where: { leadId: lead.id, sourceType: "quadrant_periodic", status: "pending" },
    });
    expect(futureTasks).toHaveLength(1);
    expect(futureTasks[0]!.title).toBe("四象限周期跟进（B·60天）");
  });

  it("recalc 对画像未变化的客户不产生事件与任务变动（幂等无噪声）", async () => {
    const lead = await createLeadFixture({ quadrant: "a" });
    const result = await recalcFollowUpPlan(lead.id, "manual_recalc", admin.value!.id);
    // 无旧计划可取消；重建恰好生成一条画像补充任务（createdCycleKeys=1）
    expect(result.canceledTaskIds).toHaveLength(0);
    expect(result.createdCycleKeys).toHaveLength(1);
    // 第二次：取消后重建同月画像任务（cycleKey 同月）——有效行唯一，旧行已取消
    const result2 = await recalcFollowUpPlan(lead.id, "manual_recalc", admin.value!.id);
    expect(result2.canceledTaskIds).toHaveLength(1);
    expect(result2.createdCycleKeys).toHaveLength(1);
    expect(await pendingAutoTasks(lead.id)).toHaveLength(1);
  });
});

describe("生成引擎：任务中心口径", () => {
  it("验收⑩：生成的今天到期任务计入今日视图、不计逾期", async () => {
    const month = currentExpiryMonth(new Date());
    const lead = await createLeadFixture({
      quadrant: "a",
      expiryMonth: addExpiryMonths(month, 3),
    });
    await runTaskGeneration({ leadIds: [lead.id], actorId: admin.value!.id });

    const result = await listTasks(admin.value!, {
      view: "today",
      status: "all",
      sourceType: "all",
      page: 1,
      pageSize: 50,
    });
    const generated = result.items.find(
      (task) => task.leadId === lead.id && task.sourceType === "expiry_monthly",
    );
    expect(generated).toBeDefined();
    expect(result.counts.overdue).toBeGreaterThanOrEqual(0);
    // 生成任务的到期日 = 今天（上海日历日）00:00，落今日窗口
    expect(shanghaiDate(generated!.dueAt)).toBe(shanghaiDate(new Date()));
  });
});
