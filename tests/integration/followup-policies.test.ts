import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { prisma } from "@/server/db";
import {
  cleanupTestUsers,
  createTestUser,
  getPresetStage,
  uniqueSuffix,
  type TestUser,
} from "./helpers";
import {
  listFollowUpPolicies,
  updateFollowUpPolicies,
} from "@/server/services/followup-policies";
import { ApiError } from "@/server/http/api";

// V2.0-T05 跟进策略验收项（实施计划 §8）：
// ① 仅管理员可写（销售 403）；系统月度策略行只读不可停用（P6）
// ② intervalDays≤0/366 Schema 拒绝（单测固化）；未知 id 404、重复 id 400
// ③ 改 A 周期 30→20 → 审计留痕 + 命中客户 pending 象限周期任务被取消
//    （original_due_at 留存）+ plan_changed 事件；历史 done 任务不变；
//    won/closed 终态客户不取消（历史不可变，§4.5 防重 #4）
// ⑤ seed 预置 5 行（A30/B60/C14/D90 + 系统月度 isSystem）；幂等由运行门
//    （db:seed 连跑两次计数不变）验证，此处断言预置行的存在与默认值。

const admin: { value: TestUser | null } = { value: null };

beforeAll(async () => {
  admin.value = await createTestUser("admin");
});

afterAll(cleanupTestUsers);

// 测试直接落库的自动任务/周期行按 lead 归属回收（helpers 清理 users→leads 级联）
const createdLeadIds: string[] = [];

async function createFixtureLead(
  ownerId: string,
  quadrant: "a" | "b" | "c" | "d" | null,
): Promise<string> {
  const stage = await getPresetStage("to_contact");
  const lead = await prisma.lead.create({
    data: {
      name: `T05 策略夹具 ${uniqueSuffix()}`,
      ownerId,
      stageId: stage.id,
      quadrantCode: quadrant,
    },
    select: { id: true },
  });
  createdLeadIds.push(lead.id);
  return lead.id;
}

async function createAutoTaskFixture(params: {
  leadId: string;
  policyId: string;
  sourceType: "quadrant_periodic" | "expiry_monthly" | "profile_gap";
  status?: "pending" | "done";
  cycleKey: string;
}) {
  const dueAt = new Date(Date.now() + 3 * 24 * 3600 * 1000);
  const task = await prisma.task.create({
    data: {
      leadId: params.leadId,
      assigneeId: admin.value!.id,
      createdBy: admin.value!.id,
      type: "follow_up",
      title: "T05 自动任务夹具",
      dueAt,
      status: params.status ?? "pending",
      sourceType: params.sourceType,
      autoGenerated: true,
      priority: 5,
      ...(params.status === "done" ? { completedAt: new Date() } : {}),
    },
  });
  const cycle = await prisma.followUpCycle.create({
    data: {
      leadId: params.leadId,
      policyId: params.policyId,
      cycleKey: params.cycleKey,
      plannedDate: new Date("2026-11-01T00:00:00.000Z"),
      taskId: task.id,
      status: params.status === "done" ? "done" : "task_created",
    },
  });
  // 回填任务侧的周期引用（真实链路由生成引擎在同一事务内互指）
  await prisma.task.update({ where: { id: task.id }, data: { cycleId: cycle.id } });
  return { task, cycle };
}

afterAll(async () => {
  // 回收顺序按外键方向：任务（引用 cycle/policy）→ 周期行 → 事件 → 线索
  if (createdLeadIds.length > 0) {
    await prisma.task.deleteMany({ where: { leadId: { in: createdLeadIds } } });
    await prisma.followUpCycle.deleteMany({ where: { leadId: { in: createdLeadIds } } });
    await prisma.leadEvent.deleteMany({ where: { leadId: { in: createdLeadIds } } });
    await prisma.lead.deleteMany({ where: { id: { in: createdLeadIds } } });
  }
  await prisma.auditLog.deleteMany({
    where: { action: "settings.followup_policy_updated" },
  });
  // 恢复 A 策略默认周期（后续运行可重复）
  await prisma.followUpPolicy.updateMany({
    where: { quadrantCode: "a" },
    data: { intervalDays: 30, isActive: true },
  });
});

async function expectApiError(
  fn: () => Promise<unknown>,
  status: number,
  code?: string,
): Promise<void> {
  try {
    await fn();
  } catch (error) {
    if (error instanceof ApiError) {
      expect(error.status).toBe(status);
      if (code) {
        expect(error.code).toBe(code);
      }
      return;
    }
    throw error;
  }
  throw new Error("预期抛出 ApiError，但未抛出");
}

describe("跟进策略：权限与预置行", () => {
  it("仅管理员可写：销售 403", async () => {
    const sales = await createTestUser("sales");
    const policies = await listFollowUpPolicies();
    const quadrantPolicy = policies.find((p) => p.quadrantCode === "a")!;
    await expectApiError(
      () =>
        updateFollowUpPolicies(sales, {
          policies: [
            {
              id: quadrantPolicy.id,
              intervalDays: 20,
              taskType: "follow_up",
              advanceDays: 0,
              isActive: true,
            },
          ],
        }),
      403,
    );
  });

  it("seed 预置 5 行：象限 A30/B60/C14/D90 + 系统月度 isSystem 只读行", async () => {
    const policies = await listFollowUpPolicies();
    expect(policies).toHaveLength(5);
    const byQuadrant = new Map(policies.map((p) => [p.quadrantCode, p]));
    expect(byQuadrant.get("a")!.intervalDays).toBe(30);
    expect(byQuadrant.get("b")!.intervalDays).toBe(60);
    expect(byQuadrant.get("c")!.intervalDays).toBe(14);
    expect(byQuadrant.get("d")!.intervalDays).toBe(90);
    const system = policies.find((p) => p.isSystem)!;
    expect(system.quadrantCode).toBeNull();
    expect(system.intervalDays).toBe(30);
    expect(system.isActive).toBe(true);
    expect(system.name).toContain("系统强制");
  });
});

describe("跟进策略：保存校验", () => {
  it("系统月度策略行只读：尝试修改 400 policy_system_readonly", async () => {
    const policies = await listFollowUpPolicies();
    const system = policies.find((p) => p.isSystem)!;
    await expectApiError(
      () =>
        updateFollowUpPolicies(admin.value!, {
          policies: [
            {
              id: system.id,
              intervalDays: 15,
              taskType: "follow_up",
              advanceDays: 0,
              isActive: false,
            },
          ],
        }),
      400,
      "policy_system_readonly",
    );
    const after = await prisma.followUpPolicy.findUniqueOrThrow({
      where: { id: system.id },
    });
    expect(after.intervalDays).toBe(30);
    expect(after.isActive).toBe(true);
  });

  it("未知策略 id → 404；同一策略重复提交 → 400 policy_duplicate", async () => {
    const policies = await listFollowUpPolicies();
    const a = policies.find((p) => p.quadrantCode === "a")!;
    await expectApiError(
      () =>
        updateFollowUpPolicies(admin.value!, {
          policies: [
            {
              id: "00000000-0000-4000-8000-000000000000",
              intervalDays: 20,
              taskType: "follow_up",
              advanceDays: 0,
              isActive: true,
            },
          ],
        }),
      404,
    );
    await expectApiError(
      () =>
        updateFollowUpPolicies(admin.value!, {
          policies: [
            {
              id: a.id,
              intervalDays: 20,
              taskType: "follow_up",
              advanceDays: 0,
              isActive: true,
            },
            {
              id: a.id,
              intervalDays: 25,
              taskType: "follow_up",
              advanceDays: 0,
              isActive: true,
            },
          ],
        }),
      400,
      "policy_duplicate",
    );
  });

  it("无变化的保存不产生审计、不受影响客户为 0", async () => {
    const policies = await listFollowUpPolicies();
    const a = policies.find((p) => p.quadrantCode === "a")!;
    const result = await updateFollowUpPolicies(admin.value!, {
      policies: [
        {
          id: a.id,
          intervalDays: a.intervalDays,
          taskType: a.taskType,
          advanceDays: a.advanceDays,
          isActive: a.isActive,
        },
      ],
    });
    expect(result.affectedLeads).toBe(0);
    const audits = await prisma.auditLog.count({
      where: { action: "settings.followup_policy_updated" },
    });
    expect(audits).toBe(0);
  });
});

describe("跟进策略：保存后命中客户重算（取消侧）", () => {
  it("改 A 周期 30→20：审计 from/to；命中 A 客户 pending 周期任务取消+周期行作废+plan_changed；done 历史与终态客户不动", async () => {
    const policies = await listFollowUpPolicies();
    const a = policies.find((p) => p.quadrantCode === "a")!;
    expect(a.intervalDays).toBe(30);

    // 夹具：A 象限活跃客户（pending+done 各一条周期任务）、won 终态客户（pending）
    const activeLead = await createFixtureLead(admin.value!.id, "a");
    const wonStage = await getPresetStage("won");
    const wonLead = await prisma.lead.create({
      data: {
        name: `T05 终态夹具 ${uniqueSuffix()}`,
        ownerId: admin.value!.id,
        stageId: wonStage.id,
        quadrantCode: "a",
      },
      select: { id: true },
    });
    createdLeadIds.push(wonLead.id);

    const pending = await createAutoTaskFixture({
      leadId: activeLead,
      policyId: a.id,
      sourceType: "quadrant_periodic",
      cycleKey: "1",
    });
    const done = await createAutoTaskFixture({
      leadId: activeLead,
      policyId: a.id,
      sourceType: "quadrant_periodic",
      status: "done",
      cycleKey: "2",
    });
    const wonTask = await createAutoTaskFixture({
      leadId: wonLead.id,
      policyId: a.id,
      sourceType: "quadrant_periodic",
      cycleKey: "1",
    });

    const result = await updateFollowUpPolicies(admin.value!, {
      policies: [
        {
          id: a.id,
          intervalDays: 20,
          taskType: a.taskType,
          advanceDays: a.advanceDays,
          isActive: a.isActive,
        },
      ],
    });
    // 只有非终态的活跃 A 客户纳入重算；won 终态客户不随策略保存重算
    // （其 pending 自动任务由阶段流转触发的重算负责取消，防重 #4）
    expect(result.affectedLeads).toBe(1);

    // 策略行更新
    const updated = result.policies.find((p) => p.quadrantCode === "a")!;
    expect(updated.intervalDays).toBe(20);

    // 审计 from/to 快照
    const audit = await prisma.auditLog.findFirstOrThrow({
      where: {
        action: "settings.followup_policy_updated",
        objectId: a.id,
      },
      orderBy: { createdAt: "desc" },
    });
    const detail = audit.detail as {
      from: { intervalDays: number };
      to: { intervalDays: number };
    };
    expect(detail.from.intervalDays).toBe(30);
    expect(detail.to.intervalDays).toBe(20);

    // pending 自动任务取消 + original_due_at 留存原计划时间；周期行作废
    const canceledTask = await prisma.task.findUniqueOrThrow({
      where: { id: pending.task.id },
    });
    expect(canceledTask.status).toBe("canceled");
    expect(canceledTask.originalDueAt?.getTime()).toBe(pending.task.dueAt.getTime());
    const canceledCycle = await prisma.followUpCycle.findUniqueOrThrow({
      where: { id: pending.cycle.id },
    });
    expect(canceledCycle.status).toBe("superseded");

    // done 历史（任务+周期行）一律不动
    const doneTask = await prisma.task.findUniqueOrThrow({
      where: { id: done.task.id },
    });
    expect(doneTask.status).toBe("done");
    expect(doneTask.originalDueAt).toBeNull();
    const doneCycle = await prisma.followUpCycle.findUniqueOrThrow({
      where: { id: done.cycle.id },
    });
    expect(doneCycle.status).toBe("done");

    // won 终态客户：任务不被取消（防重 #4；重算由阶段变化触发，策略保存不触终态）
    const wonTaskAfter = await prisma.task.findUniqueOrThrow({
      where: { id: wonTask.task.id },
    });
    expect(wonTaskAfter.status).toBe("pending");

    // plan_changed 事件（reason=policy_updated，canceledTaskIds 留痕）
    const event = await prisma.leadEvent.findFirstOrThrow({
      where: { leadId: activeLead, eventType: "plan_changed" },
    });
    expect((event.detail as { reason: string }).reason).toBe("policy_updated");
    expect(
      (event.detail as { canceledTaskIds: string[] }).canceledTaskIds,
    ).toContain(pending.task.id);
    // won 客户无 plan_changed 事件
    const wonEvents = await prisma.leadEvent.count({
      where: { leadId: wonLead.id, eventType: "plan_changed" },
    });
    expect(wonEvents).toBe(0);
  });

  it("停用策略同样取消命中客户的 pending 周期任务；到期月度任务不受象限策略保存影响", async () => {
    const policies = await listFollowUpPolicies();
    const d = policies.find((p) => p.quadrantCode === "d")!;
    const system = policies.find((p) => p.isSystem)!;
    const lead = await createFixtureLead(admin.value!.id, "d");
    const periodic = await createAutoTaskFixture({
      leadId: lead,
      policyId: d.id,
      sourceType: "quadrant_periodic",
      cycleKey: "1",
    });
    const monthly = await createAutoTaskFixture({
      leadId: lead,
      policyId: system.id,
      sourceType: "expiry_monthly",
      cycleKey: "M2026-11",
    });

    await updateFollowUpPolicies(admin.value!, {
      policies: [
        {
          id: d.id,
          intervalDays: d.intervalDays,
          taskType: d.taskType,
          advanceDays: d.advanceDays,
          isActive: false,
        },
      ],
    });

    expect((await prisma.task.findUniqueOrThrow({ where: { id: periodic.task.id } })).status).toBe(
      "canceled",
    );
    // 月度任务是系统强制规则，不随象限策略停用被取消
    expect((await prisma.task.findUniqueOrThrow({ where: { id: monthly.task.id } })).status).toBe(
      "pending",
    );

    // 恢复 D 启用
    await prisma.followUpPolicy.update({ where: { id: d.id }, data: { isActive: true } });
  });
});
