// 首页经营视图服务（V2.0-T09，PRD 模块七 / UIUX §5.6）。
//
// 四顶卡：今日应跟进（任务口径，与任务中心同一实现）/ 软件半年内到期 /
// 画像待完善 / 已逾期任务——计数与对应列表筛选同一 where（口径必然一致）。
// 五个主列表（每行字段 = PRD 模块七全集）：本次联系原因与推荐沟通内容
// 均为服务端规则文案（lib/workbench.ts），前端不自算。
// 数据范围一律经 leadReadScope；终态客户（won/closed）不进作战列表
// （与任务生成器同一口径）。

const CORE_FIELD_LABELS: Map<string, string> = new Map(
  BUILTIN_LEAD_FIELDS.map((field) => [field.key, field.label]),
);

/** 应跟窗口：pending 自动任务截止日 ≤ 今天+7 天视为"当前应跟"（含逾期） */
const FOCUS_WINDOW_DAYS = 7;

export interface WorkbenchRow {
  leadId: string;
  name: string;
  cityIndustry: string | null;
  currentSystem: string | null;
  quadrant: QuadrantCode | null;
  /** ExpiryChip 文案（年月+窗口语义；未知=null） */
  expiryDisplay: string | null;
  /** 最近联系（相对时间；从未联系=null） */
  lastContactDisplay: string | null;
  /** 本次联系原因（规则文案，必显） */
  reason: string;
  /** 推荐沟通内容（规则模板） */
  talkTrack: string;
  nextAction: {
    taskId: string;
    title: string;
    dueDisplay: string;
    sourceLabel: string | null;
    sourceType: string;
  } | null;
  /** 画像待完善 Tab：缺失核心字段清单 */
  coreMissing: string[];
}

export interface OperationsWorkbench {
  cards: {
    /** 今日应跟进（今日待办任务数，任务口径） */
    followToday: number;
    /** 软件半年内到期客户数 */
    expiringSoon: number;
    /** 画像待完善客户数 */
    profileGap: number;
    /** 已逾期任务数 */
    overdueTasks: number;
  };
  activeTab: WorkbenchTabKey;
  tabs: Record<WorkbenchTabKey, WorkbenchRow[]>;
}

function expiryStatusOf(
  verifications: { leadId: string; fieldKey: string; status: string }[],
  leadId: string,
): string {
  return (
    verifications.find(
      (row) => row.leadId === leadId && row.fieldKey === "contract_expiry",
    )?.status ?? "unknown"
  );
}

/** 批量装载行的公共上下文：到期核实状态 + pending 自动任务（最早截止在前） */
async function loadRowContext(
  leadIds: string[],
): Promise<{
  expiryStatus: Map<string, string>;
  pendingTasks: Map<string, {
    id: string;
    title: string;
    dueAt: Date;
    sourceType: string;
  }[]>;
}> {
  if (leadIds.length === 0) {
    return { expiryStatus: new Map(), pendingTasks: new Map() };
  }
  const [verifications, tasks] = await Promise.all([
    prisma.leadFieldVerification.findMany({
      where: { leadId: { in: leadIds }, fieldKey: "contract_expiry" },
      select: { leadId: true, fieldKey: true, status: true },
    }),
    prisma.task.findMany({
      where: { leadId: { in: leadIds }, status: "pending", autoGenerated: true },
      select: { id: true, leadId: true, title: true, dueAt: true, sourceType: true },
      orderBy: { dueAt: "asc" },
    }),
  ]);
  const pendingTasks = new Map<string, {
    id: string;
    title: string;
    dueAt: Date;
    sourceType: string;
  }[]>();
  for (const task of tasks) {
    const bucket = pendingTasks.get(task.leadId) ?? [];
    bucket.push({
      id: task.id,
      title: task.title,
      dueAt: task.dueAt,
      sourceType: task.sourceType,
    });
    pendingTasks.set(task.leadId, bucket);
  }
  return {
    expiryStatus: new Map(verifications.map((row) => [row.leadId, row.status])),
    pendingTasks,
  };
}

function toRow(
  lead: {
    id: string;
    name: string;
    city: string | null;
    industry: string | null;
    currentSystem: string | null;
    quadrantCode: QuadrantCode | null;
    contractExpiry: Date | null;
    lastContactAt: Date | null;
  },
  context: {
    expiryStatus: Map<string, string>;
    pendingTasks: Map<string, {
      id: string;
      title: string;
      dueAt: Date;
      sourceType: string;
    }[]>;
  },
  now: Date,
  options: { reason: string; coreMissing?: string[] },
): WorkbenchRow {
  const expiryStatus = context.expiryStatus.get(lead.id) ?? "unknown";
  const window = expiryWindow(lead.contractExpiry, now, { status: expiryStatus });
  const tasks = context.pendingTasks.get(lead.id) ?? [];
  const nextTask = tasks[0] ?? null;
  const cityIndustry =
    [lead.city, lead.industry].filter(Boolean).join(" · ") || null;
  return {
    leadId: lead.id,
    name: lead.name,
    cityIndustry,
    currentSystem: lead.currentSystem,
    quadrant: lead.quadrantCode,
    expiryDisplay: lead.contractExpiry
      ? formatExpiryChip(lead.contractExpiry, now, { status: expiryStatus })
      : null,
    lastContactDisplay: lead.lastContactAt
      ? formatRelativeShanghai(lead.lastContactAt, now)
      : null,
    reason: options.reason,
    talkTrack: recommendedTalkTrack({
      quadrant: lead.quadrantCode,
      expiryWindow: window,
    }),
    nextAction: nextTask
      ? {
          taskId: nextTask.id,
          title: nextTask.title,
          dueDisplay: toShanghaiDateString(nextTask.dueAt),
          sourceType: nextTask.sourceType,
          sourceLabel: TASK_SOURCE_BADGE_LABELS[nextTask.sourceType] ?? null,
        }
      : null,
    coreMissing: options.coreMissing ?? [],
  };
}

const workbenchLeadSelect = {
  id: true,
  name: true,
  city: true,
  industry: true,
  currentSystem: true,
  quadrantCode: true,
  contractExpiry: true,
  lastContactAt: true,
} as const;

/** Tab 1：今日优先（T10 规则引擎输出，理由必显） */
async function loadTodayRows(user: AuthUser, now: Date): Promise<WorkbenchRow[]> {
  const priorities = await suggestPriorityLeads(user, { now, limit: 5 });
  const context = await loadRowContext(priorities.map((row) => row.leadId));
  const leads = priorities.length
    ? await prisma.lead.findMany({
        where: { id: { in: priorities.map((row) => row.leadId) } },
        select: workbenchLeadSelect,
      })
    : [];
  const leadById = new Map(leads.map((lead) => [lead.id, lead]));
  const rows: WorkbenchRow[] = [];
  for (const priority of priorities) {
    const lead = leadById.get(priority.leadId);
    if (!lead) {
      continue;
    }
    rows.push(
      toRow(lead, context, now, { reason: priority.reasons.join("；") }),
    );
  }
  return rows;
}

/** Tab 2：月度必跟（半年内到期含已过期，当月应跟；已过期在最前） */
async function loadMonthlyRows(user: AuthUser, now: Date): Promise<WorkbenchRow[]> {
  const scope = leadReadScope(user);
  const month = currentExpiryMonth(now);
  const upperBound = expiryMonthToUtcDate(addExpiryMonths(month, 6));
  const leads = await prisma.lead.findMany({
    where: {
      deletedAt: null,
      ...scope,
      contractExpiry: { lte: upperBound },
      stage: { semanticKey: { notIn: [...TASK_GENERATION_TERMINAL_STAGES] } },
    },
    select: workbenchLeadSelect,
    orderBy: { contractExpiry: "asc" },
    take: 40,
  });
  const context = await loadRowContext(leads.map((lead) => lead.id));
  const rows: WorkbenchRow[] = [];
  for (const lead of leads) {
    const expiryStatus = context.expiryStatus.get(lead.id) ?? "unknown";
    // 到期核实状态 unknown 视同未知（§4.2），不进月度必跟
    if (expiryStatus === "unknown" && lead.contractExpiry) {
      continue;
    }
    rows.push(
      toRow(lead, context, now, {
        reason: autoTaskReasonLabel("expiry_monthly", {
          contractExpiry: lead.contractExpiry,
          expiryVerificationStatus: expiryStatus,
          quadrant: lead.quadrantCode,
          intervalDays: null,
          now,
        }) ?? "软件到期窗口内，按系统月度规则跟进",
      }),
    );
    if (rows.length >= 10) {
      break;
    }
  }
  return rows;
}

/** Tab 3：画像待完善（核心字段未全核实；缺失清单必显） */
async function loadGapRows(user: AuthUser, now: Date): Promise<WorkbenchRow[]> {
  const scope = leadReadScope(user);
  const leads = await prisma.lead.findMany({
    where: {
      deletedAt: null,
      ...scope,
      OR: [{ profileStatus: "incomplete" }, { profileStatus: null }],
      stage: { semanticKey: { notIn: [...TASK_GENERATION_TERMINAL_STAGES] } },
    },
    select: { ...workbenchLeadSelect, fieldVerifications: true },
    orderBy: { updatedAt: "desc" },
    take: 10,
  });
  const context = await loadRowContext(leads.map((lead) => lead.id));
  return leads.map((lead) => {
    const verifiedKeys = new Set(
      lead.fieldVerifications
        .filter((row) => row.status === "confirmed" || row.status === "stated")
        .map((row) => row.fieldKey),
    );
    const missing = PROFILE_CORE_FIELDS.filter((key) => !verifiedKeys.has(key)).map(
      (key) => CORE_FIELD_LABELS.get(key) ?? key,
    );
    return toRow(lead, context, now, {
      reason: profileGapReason(missing),
      coreMissing: missing,
    });
  });
}

/** Tab 4/5：四象限重点（A/C）与长期培育（B/D）——一周内有应跟的自动任务 */
async function loadQuadrantRows(
  user: AuthUser,
  quadrants: QuadrantCode[],
  now: Date,
  limit: number,
): Promise<WorkbenchRow[]> {
  const scope = leadReadScope(user);
  const dueBefore = new Date(now.getTime() + FOCUS_WINDOW_DAYS * 24 * 3600 * 1000);
  const tasks = await prisma.task.findMany({
    where: {
      status: "pending",
      autoGenerated: true,
      dueAt: { lte: dueBefore },
      lead: {
        deletedAt: null,
        ...scope,
        quadrantCode: { in: quadrants },
        stage: { semanticKey: { notIn: [...TASK_GENERATION_TERMINAL_STAGES] } },
      },
    },
    include: {
      lead: { select: workbenchLeadSelect },
      policy: { select: { intervalDays: true } },
    },
    orderBy: { dueAt: "asc" },
    take: limit * 4,
  });
  const seen = new Set<string>();
  const picked: (typeof tasks)[number][] = [];
  for (const task of tasks) {
    if (seen.has(task.leadId)) {
      continue;
    }
    seen.add(task.leadId);
    picked.push(task);
    if (picked.length >= limit) {
      break;
    }
  }
  const context = await loadRowContext(picked.map((task) => task.leadId));
  return picked.map((task) => {
    const expiryStatus = context.expiryStatus.get(task.lead.id) ?? "unknown";
    return toRow(task.lead, context, now, {
      reason:
        autoTaskReasonLabel(task.sourceType, {
          contractExpiry: task.lead.contractExpiry,
          expiryVerificationStatus: expiryStatus,
          quadrant: task.lead.quadrantCode,
          intervalDays: task.policy?.intervalDays ?? null,
          now,
        }) ?? "系统按跟进策略安排的本轮跟进",
    });
  });
}

/**
 * 经营视图汇总（首页 SSR 专用；计数与对应列表筛选同一 where）。
 * tabs 只计算当前激活的 Tab（性能感知：首屏只渲染当前列表，UIUX §5.6）。
 */
export async function getOperationsWorkbench(
  user: AuthUser,
  options: { now?: Date; tab?: string } = {},
): Promise<OperationsWorkbench> {
  const now = options.now ?? new Date();
  const activeTab: WorkbenchTabKey =
    options.tab && isWorkbenchTab(options.tab) ? options.tab : WORKBENCH_TAB_DEFAULT;

  const [taskCounts, expiryCounts, profileGap] = await Promise.all([
    getTaskCounts(user, now),
    countLeadsByExpiryView(user, now),
    prisma.lead.count({
      where: {
        deletedAt: null,
        ...leadReadScope(user),
        OR: [{ profileStatus: "incomplete" }, { profileStatus: null }],
      },
    }),
  ]);

  const tabs: Record<WorkbenchTabKey, WorkbenchRow[]> = {
    today: [],
    monthly: [],
    gap: [],
    focus: [],
    nurture: [],
  };
  switch (activeTab) {
    case "today":
      tabs.today = await loadTodayRows(user, now);
      break;
    case "monthly":
      tabs.monthly = await loadMonthlyRows(user, now);
      break;
    case "gap":
      tabs.gap = await loadGapRows(user, now);
      break;
    case "focus":
      tabs.focus = await loadQuadrantRows(user, ["a", "c"], now, 5);
      break;
    case "nurture":
      tabs.nurture = await loadQuadrantRows(user, ["b", "d"], now, 5);
      break;
  }

  return {
    cards: {
      followToday: taskCounts.today,
      expiringSoon: expiryCounts.within_6m,
      profileGap,
      overdueTasks: taskCounts.overdue,
    },
    activeTab,
    tabs,
  };
}
