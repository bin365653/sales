import { Prisma, Task } from "@prisma/client";
import { prisma } from "@/server/db";

// 跟进计划取消核心（V2.0-T05，实施计划 §4.6 动态重算的取消半边）。
//
// 策略修改（T05）/五个触发字段变化（T06 recalcFollowUpPlan）时，取消客户名下
// 「未来未执行」的自动任务并作废对应周期行——只调整未来未执行的计划，
// 不修改历史任务（V2.2 第五节红线）：
// - 取消 = pending → canceled，original_due_at 留存原计划时间（审计可查）；
// - 周期行随任务作废置 superseded（历史行保留，不物理删除）；
// - done/canceled 的既有任务与周期行一律不动；
// - plan_changed 事件由调用方写入（detail 附 reason；T06 recalc 重建后
//   再附 createdCycleKeys），本模块只做状态变更并返回留痕素材。
//
// 重新生成不在此处发生：生成是幂等引擎（runTaskGeneration，T06）的职责，
// 惰性触发/手动触发/单客户重算都会在取消后按新口径补齐计划（§4.5）。

export type Db = Prisma.TransactionClient | typeof prisma;

export interface CancelAutoPlansResult {
  /** 本次取消的自动任务 id（plan_changed 事件 detail.canceledTaskIds） */
  canceledTaskIds: string[];
  /** 作废周期行的 cycleKey（plan_changed 事件 detail.supersededCycleKeys） */
  supersededCycleKeys: string[];
}

/**
 * 取消客户名下 pending 的指定来源自动任务，并作废其周期行。
 * 必须在调用方事务内执行（与触发字段写入同事务，§4.6）。
 */
export async function cancelPendingAutoPlans(
  tx: Db,
  leadId: string,
  sources: readonly Task["sourceType"][],
): Promise<CancelAutoPlansResult> {
  if (sources.length === 0) {
    return { canceledTaskIds: [], supersededCycleKeys: [] };
  }
  const pendingTasks = await tx.task.findMany({
    where: {
      leadId,
      status: "pending",
      autoGenerated: true,
      sourceType: { in: [...sources] },
    },
    select: { id: true, cycleId: true },
  });
  if (pendingTasks.length === 0) {
    return { canceledTaskIds: [], supersededCycleKeys: [] };
  }

  const canceledTaskIds: string[] = [];
  const cycleIds: string[] = [];
  for (const task of pendingTasks) {
    // 逐条条件更新（仅 pending 命中）：并发下任务可能刚被完成/取消——
    // 该场景不报错（取消目标已消失，语义达成），只跳过；
    // 原计划时间在下方统一留存（只写为空者，二次取消不覆盖首次留痕）
    const updated = await tx.task.updateMany({
      where: { id: task.id, status: "pending" },
      data: { status: "canceled" },
    });
    if (updated.count === 1) {
      canceledTaskIds.push(task.id);
      if (task.cycleId) {
        cycleIds.push(task.cycleId);
      }
    }
  }

  // 原计划时间留存：取消前读一次 dueAt 写回 original_due_at（只写为空者，
  // 二次取消不覆盖首次留痕）
  if (canceledTaskIds.length > 0) {
    const rows = await tx.task.findMany({
      where: { id: { in: canceledTaskIds }, originalDueAt: null },
      select: { id: true, dueAt: true },
    });
    for (const row of rows) {
      await tx.task.update({
        where: { id: row.id },
        data: { originalDueAt: row.dueAt },
      });
    }
  }

  const supersededCycleKeys: string[] = [];
  if (cycleIds.length > 0) {
    const cycles = await tx.followUpCycle.findMany({
      where: { id: { in: cycleIds }, status: { in: ["planned", "task_created"] as const } },
      select: { id: true, cycleKey: true },
    });
    for (const cycle of cycles) {
      await tx.followUpCycle.update({
        where: { id: cycle.id },
        data: { status: "superseded" },
      });
      supersededCycleKeys.push(cycle.cycleKey);
    }
  }

  return { canceledTaskIds, supersededCycleKeys };
}
